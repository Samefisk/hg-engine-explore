.include "asm/include/battle_commands.inc"

.data

_000:
    IfSameSide BATTLER_CATEGORY_ATTACKER, BATTLER_CATEGORY_PLAYER, _006
    CompareVarToValue OPCODE_FLAG_SET, BSCRIPT_VAR_BATTLE_TYPE, BATTLE_TYPE_TRAINER, _004
    PrintMessage 1642, TAG_NICKNAME_ABILITY, BATTLER_CATEGORY_ATTACKER, BATTLER_CATEGORY_ATTACKER
    GoTo _008

_004:
    PrintMessage 1643, TAG_NICKNAME_ABILITY, BATTLER_CATEGORY_ATTACKER, BATTLER_CATEGORY_ATTACKER
    GoTo _008

_006:
    PrintMessage 1641, TAG_NICKNAME_ABILITY, BATTLER_CATEGORY_ATTACKER, BATTLER_CATEGORY_ATTACKER

_008:
    Wait
    WaitButtonABTime 30
    CompareMonDataToValue OPCODE_EQU, BATTLER_CATEGORY_DEFENDER, BMON_DATA_ABILITY, ABILITY_WATER_ABSORB, _waterAbsorb
    CompareMonDataToValue OPCODE_EQU, BATTLER_CATEGORY_DEFENDER, BMON_DATA_ABILITY, ABILITY_DRY_SKIN, _waterAbsorb
    CompareMonDataToValue OPCODE_EQU, BATTLER_CATEGORY_DEFENDER, BMON_DATA_ABILITY, ABILITY_STORM_DRAIN, _stormDrain
    GoTo _020

_waterAbsorb:
    UpdateMonDataFromVar OPCODE_GET, BATTLER_CATEGORY_DEFENDER, BMON_DATA_MAXHP, BSCRIPT_VAR_HP_CALC
    DivideVarByValue BSCRIPT_VAR_HP_CALC, 4
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_MSG_BATTLER_TEMP, BSCRIPT_VAR_BATTLER_TARGET
    Call BATTLE_SUBSCRIPT_ABILITY_RESTORES_HP
    GoTo _112

_stormDrain:
    Call BATTLE_SUBSCRIPT_LIGHTNING_ROD_REDIRECTED
    GoTo _112

_020:
    CalcDamage
    CompareVarToValue OPCODE_FLAG_SET, BSCRIPT_VAR_MOVE_STATUS_FLAGS, MOVE_STATUS_DID_NOT_HIT, _104
    PlayMoveAnimation BATTLER_CATEGORY_ATTACKER
    Wait
    CheckSubstitute BATTLER_CATEGORY_DEFENDER, _072
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_HP_CALC, BSCRIPT_VAR_DAMAGE
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_PHYSICAL_DAMAGE_TAKEN, BSCRIPT_VAR_DAMAGE
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_MSG_BATTLER_TEMP, BSCRIPT_VAR_BATTLER_TARGET
    CheckHoldOnWith1HP BATTLER_CATEGORY_MSG_TEMP
    Call BATTLE_SUBSCRIPT_UPDATE_HP
    Call BATTLE_SUBSCRIPT_MOVE_FOLLOWUP_MESSAGE
    CompareMonDataToValue OPCODE_EQU, BATTLER_CATEGORY_DEFENDER, BMON_DATA_HP, 0, _091
    TriggerAbilityOnHit _052
    CallFromVar BSCRIPT_VAR_TEMP_DATA

_052:
    TriggerHeldItemOnHit _056
    CallFromVar BSCRIPT_VAR_TEMP_DATA

_056:
    UpdateVar OPCODE_FLAG_ON, BSCRIPT_VAR_BATTLE_STATUS, BATTLE_STATUS_MOVE_SUCCESSFUL
    TriggerHeldItemOnPivotMove _064
    CallFromVar BSCRIPT_VAR_TEMP_DATA

_064:
    UpdateVar OPCODE_FLAG_OFF, BSCRIPT_VAR_BATTLE_STATUS, BATTLE_STATUS_MOVE_SUCCESSFUL
    GoTo _112

_072:
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_TEMP_DATA, BSCRIPT_VAR_DAMAGE
    UpdateVar OPCODE_MUL, BSCRIPT_VAR_TEMP_DATA, -1
    CompareMonDataToVar OPCODE_LTE, BATTLER_CATEGORY_DEFENDER, BMON_DATA_SUBSTITUTE_HP, BSCRIPT_VAR_TEMP_DATA, _080
    GoTo _084

_080:
    UpdateMonData OPCODE_FLAG_OFF, BATTLER_CATEGORY_DEFENDER, BMON_DATA_STATUS2, STATUS2_SUBSTITUTE

_084:
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_MSG_BATTLER_TEMP, BSCRIPT_VAR_BATTLER_TARGET
    Call BATTLE_SUBSCRIPT_HIT_SUBSTITUTE
    Call BATTLE_SUBSCRIPT_MOVE_FOLLOWUP_MESSAGE
    GoTo _112

_091:
    Call BATTLE_SUBSCRIPT_FAINT_CHECK_DESTINY_BOND
    TriggerAbilityOnHit _095
    CallFromVar BSCRIPT_VAR_TEMP_DATA

_095:
    TriggerHeldItemOnHit _099
    CallFromVar BSCRIPT_VAR_TEMP_DATA

_099:
    UpdateVar OPCODE_FLAG_ON, BSCRIPT_VAR_BATTLE_STATUS, BATTLE_STATUS_MOVE_SUCCESSFUL
    TriggerHeldItemOnPivotMove _107
    CallFromVar BSCRIPT_VAR_TEMP_DATA

_107:
    UpdateVar OPCODE_FLAG_OFF, BSCRIPT_VAR_BATTLE_STATUS, BATTLE_STATUS_MOVE_SUCCESSFUL
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_TEMP_DATA, BSCRIPT_VAR_BATTLER_FAINTED
    UpdateVar OPCODE_SET, BSCRIPT_VAR_BATTLER_FAINTED, BATTLER_PLAYER
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_CALC_TEMP, BSCRIPT_VAR_BATTLE_STATUS_2
    UpdateVar OPCODE_RIGHT_SHIFT, BSCRIPT_VAR_CALC_TEMP, 0x0000001C
    UpdateVar OPCODE_FLAG_OFF, BSCRIPT_VAR_BATTLE_STATUS_2, BATTLE_STATUS2_EXP_GAIN

_expLoop:
    CompareVarToValue OPCODE_FLAG_NOT, BSCRIPT_VAR_CALC_TEMP, 0x00000001, _110
    Call BATTLE_SUBSCRIPT_GRANT_EXP

_110:
    UpdateVar OPCODE_ADD, BSCRIPT_VAR_BATTLER_FAINTED, BATTLER_ENEMY
    UpdateVar OPCODE_RIGHT_SHIFT, BSCRIPT_VAR_CALC_TEMP, 0x00000001
    CompareVarToValue OPCODE_NEQ, BSCRIPT_VAR_CALC_TEMP, 0x00000000, _expLoop
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_BATTLER_FAINTED, BSCRIPT_VAR_TEMP_DATA
    Call BATTLE_SUBSCRIPT_FAINT_MON
    TryReplaceFaintedMon BATTLER_CATEGORY_DEFENDER, TRUE, _128
    IfSameSide BATTLER_CATEGORY_DEFENDER, BATTLER_CATEGORY_PLAYER, _playerFaintedReplace
    GoTo _faintedAutoReplace

_playerFaintedReplace:
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_BATTLER_SWITCH, BSCRIPT_VAR_BATTLER_TARGET
    GoToSubscript BATTLE_SUBSCRIPT_SHOW_PARTY_LIST

_faintedAutoReplace:
    SwitchAndUpdateMon BATTLER_CATEGORY_FORCED_OUT
    Wait
    PokemonSendOut BATTLER_CATEGORY_DEFENDER
    WaitTime 72
    HealthbarSlideIn BATTLER_CATEGORY_DEFENDER
    Wait
    Call BATTLE_SUBSCRIPT_HAZARDS_CHECK
    GoTo _128

_104:
    WaitButtonABTime 15
    Call BATTLE_SUBSCRIPT_MISSED
    GoTo _128

_112:
    CompareMonDataToValue OPCODE_EQU, BATTLER_CATEGORY_DEFENDER, BMON_DATA_ABILITY, ABILITY_SUCTION_CUPS, _149
    CompareMonDataToValue OPCODE_FLAG_SET, BATTLER_CATEGORY_DEFENDER, BMON_DATA_MOVE_EFFECT, MOVE_EFFECT_FLAG_INGRAIN, _149
    TryReplaceFaintedMon BATTLER_CATEGORY_DEFENDER, TRUE, _128
    GoTo _120

_120:
    TryReplaceFaintedMon BATTLER_CATEGORY_DEFENDER, TRUE, _128

_121:
    TryWhirlwind _121
    TryRestoreStatusOnSwitch BATTLER_CATEGORY_DEFENDER, _124
    UpdateMonData OPCODE_SET, BATTLER_CATEGORY_DEFENDER, BMON_DATA_STATUS, STATUS_NONE

_124:
    DeletePokemon BATTLER_CATEGORY_DEFENDER
    Wait
    HealthbarSlideOut BATTLER_CATEGORY_DEFENDER
    Wait
    IfSameSide BATTLER_CATEGORY_DEFENDER, BATTLER_CATEGORY_PLAYER, _playerForcedSwitch
    SwitchAndUpdateMon BATTLER_CATEGORY_FORCED_OUT
    Wait
    PokemonSendOut BATTLER_CATEGORY_DEFENDER
    WaitTime 72
    HealthbarSlideIn BATTLER_CATEGORY_DEFENDER
    Wait
    BufferLocalMessage BATTLER_CATEGORY_DEFENDER, 1647, TAG_NICKNAME, BATTLER_CATEGORY_DEFENDER
    PrintBufferedMessage
    Wait
    WaitButtonABTime 30
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_BATTLER_SWITCH, BSCRIPT_VAR_BATTLER_TARGET
    Call BATTLE_SUBSCRIPT_HAZARDS_CHECK
    GoTo _128

_playerForcedSwitch:
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_BATTLER_SWITCH, BSCRIPT_VAR_BATTLER_TARGET
    GoToSubscript BATTLE_SUBSCRIPT_SHOW_PARTY_LIST

_149:
    BufferLocalMessage BATTLER_CATEGORY_DEFENDER, 1644, TAG_NICKNAME, BATTLER_CATEGORY_DEFENDER
    PrintBufferedMessage
    Wait
    WaitButtonABTime 30

_128:
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_MOVE_NO_CUR, BSCRIPT_VAR_CALC_TEMP
    End
